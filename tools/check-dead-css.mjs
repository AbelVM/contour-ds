#!/usr/bin/env node
/**
 * Static CSS reachability check (R13-26).
 *
 * This is intentionally a candidate finder, not a CSS parser pretending to
 * understand runtime state. A component class is live when it appears outside
 * src/css in markup or code. Names assembled at runtime belong in the ledger
 * below until a static consumer exists.
 */

import { existsSync, readFileSync, readdirSync } from "node:fs";
import { join } from "node:path";
import { CLASS_RE } from "./lib/inventory.mjs";

const ROOT = new URL("..", import.meta.url).pathname.replace(/\/$/, "");
const CSS = join(ROOT, "src/css");

// Generated class names that cannot be found by a static consumer search.
// Keep entries singular and explain the runtime producer.
const DYNAMIC_LEDGER = {
};
const DYNAMIC_PATTERNS = [
  [/^c-[a-z0-9-]+__(empty|error|loading)$/, "generated by async state renderers"],
  [/^c-chart__band--(div-mid|div-neg|div-pos|seq-[1-7])$/, "generated from chart band data"],
  [/^c-(banner|delta|divider|side-sheet|status-light)--[a-z0-9-]+$/, "generated from a component attribute"],
  [/^c-bivariate-legend__(axis|cell|live)(--[a-z0-9-]+)?$/, "generated from bivariate legend data"],
  [/^c-chart__(band|control|missing|zero)$/, "generated from chart data"],
  [/^c-contour-plot__contour--level-[2-5]$/, "generated from contour levels"],
  [/^c-(axis__line|brownout__decorative|contour-plot__fill|landing-hero__preview-dot|time-series__point)$/, "generated by a visual renderer"],
  [/^c-activity-feed__dot--(error|info|success|warning)$/, "generated from an activity severity attribute"],
  [/^c-provenance__confidence--(high|low|medium)$/, "generated from a provenance confidence attribute"],
  [/^c-split-pane--(horizontal|vertical)$/, "generated from a split-pane orientation attribute"],
];

const withoutComments = (text) => text.replace(/\/\*[\s\S]*?\*\//g, " ");

function filesUnder(dir) {
  if (!existsSync(dir)) return [];
  return readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
    const path = join(dir, entry.name);
    return entry.isDirectory() ? filesUnder(path) : [path];
  });
}

function consumerText() {
  const roots = ["index.html", "templates", "src/js", "assets/js", "stories", "tests"];
  return roots.flatMap((name) => {
    const path = join(ROOT, name);
    return existsSync(path) && !path.endsWith(".html") && !path.endsWith(".js")
      ? filesUnder(path)
      : [path];
  }).filter((path) => existsSync(path)).map((path) => withoutComments(readFileSync(path, "utf8"))).join("\n");
}

function cssClasses() {
  const classes = new Map();
  for (const file of readdirSync(CSS).filter((name) => name.endsWith(".css"))) {
    const text = withoutComments(readFileSync(join(CSS, file), "utf8"));
    for (const match of text.matchAll(CLASS_RE)) {
      const name = match[1];
      if (!classes.has(name)) classes.set(name, new Set());
      classes.get(name).add(file);
    }
  }
  return classes;
}

function main() {
  const consumers = consumerText();
  const classes = cssClasses();
  const candidates = [...classes.keys()]
    .filter((name) => !new RegExp(`\\b${name}\\b`).test(consumers))
    .sort();
  const reasonFor = (name) => DYNAMIC_LEDGER[name] || DYNAMIC_PATTERNS.find(([pattern]) => pattern.test(name))?.[1];
  const unledgered = candidates.filter((name) => !reasonFor(name));
  const stale = Object.keys(DYNAMIC_LEDGER).filter((name) => !candidates.includes(name));

  if (process.argv.includes("--json")) {
    console.log(JSON.stringify({ cssClasses: classes.size, candidates, unledgered, stale }, null, 2));
  } else if (process.argv.includes("--report")) {
    console.log(`check-dead-css: ${classes.size} CSS classes, ${candidates.length} candidate(s)`);
    for (const name of candidates) console.log(`  ${name.padEnd(32)} ${reasonFor(name) || "*** NOT IN THE LEDGER ***"}`);
  }

  if (stale.length || unledgered.length) {
    console.error(`check-dead-css: ${stale.length + unledgered.length} ledger discrepancy(ies)`);
    for (const name of unledgered) console.error(`  candidate has no static consumer or ledger entry: .${name}`);
    for (const name of stale) console.error(`  ledger entry is no longer needed: .${name}`);
    return 1;
  }

  if (!classes.size) {
    console.error("check-dead-css: found no CSS classes, so the sweep measured nothing");
    return 1;
  }
  console.log(`check-dead-css: ${classes.size} CSS classes checked; ${candidates.length} dynamic candidate(s) accounted for. OK`);
  return 0;
}

process.exit(main());