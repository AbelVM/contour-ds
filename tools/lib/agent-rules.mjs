/**
 * The agent-rules artifact (C-47): `dist/agent-rules.json`.
 *
 * An agent generating UI with Contour needs the system's constraints in a form it can
 * read before it writes anything, and a CSS system's constraints are unusually good at
 * this: almost every rule here is already a running check rather than a style-guide
 * sentence. So the artifact is a list of rules that each name the gate enforcing them,
 * and the gate (`tools/check-agent-rules.mjs`) fails if a rule cites a check that does
 * not exist or exists but runs in no CI lane.
 *
 * That last clause is not decorative. This row originally claimed its rules were
 * "already machine-checkable" and pointed at `check-ownership`, `family-gate` and
 * `check-tokens`. Reading their assertion loops found that `check-tokens` owns the
 * census and no colour literal at all, and that `family-gate` — the only check that
 * does — was wired into no lane and hard-coded to one absolute path, so it scanned
 * whichever repo it was written in rather than the one it stood in. A rulebook that
 * repeats a claim like that would be worse than no rulebook: it launders an
 * unenforced preference into an authoritative-sounding instruction. So existence and
 * wiring are resolved from the tree at build time, and the build throws if a cited
 * gate is missing — the artifact cannot be emitted with a dangling enforcement.
 *
 * It deliberately publishes no counts. The numbers an agent needs live in
 * `contour.components.json` and `contour.tokens.json`, which are derived from
 * `tools/lib/inventory.mjs` and re-checked by their own gates; restating a count here
 * would create a second copy of one fact, which is the failure this repository keeps
 * paying for.
 */
