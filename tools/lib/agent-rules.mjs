const CI_FILE = ".github/workflows/ci.yml";

/**
 * Resolve each cited gate against the tree: it must exist, and it must be invoked in a
 * CI job. The lane is read from ci.yml rather than hardcoded, because a claim about
 * where a check runs is exactly the kind of claim that goes stale when someone moves it.
 */
export function buildAgentRules(root) {
  const ci = existsSync(join(root, CI_FILE))
    ? readFileSync(join(root, CI_FILE), "utf8")
    : (() => { throw new Error(`buildAgentRules: ${CI_FILE} is missing, so no enforcement could be verified`); })();

  const jobs = [...ci.matchAll(/^  ([a-z][\w-]*):\n    runs-on:/gm)].map((m) => m[1]);
  // Slice each job's own text between its header and the next job's, not to EOF. The
  // first version took `ci.slice(indexOf("  validate:"))`, which therefore also held
  // the contract job, so every gate — including the browser ones — was published as
  // `validate`. The artifact claims where each check runs; that claim has to be read
  // out of the file rather than assumed from the first match.
  const jobText = new Map();
  {
    const heads = [...ci.matchAll(/^  ([a-z][\w-]*):\n    runs-on:/gm)];
    for (let i = 0; i < heads.length; i += 1) {
      const from = heads[i].index;
      const to = i + 1 < heads.length ? heads[i + 1].index : ci.length;
      jobText.set(heads[i][1], ci.slice(from, to));
    }
  }
  // A gate can legitimately run in more than one job — `tools/build.mjs` runs in
  // validate, and again in contract because dist/ is gitignored so the second job has to
  // produce the artifacts it reads. Reporting only the first match published that gate
  // as `validate`, which was true but incomplete: the same class of error as naming a job
  // that does not run it. So publish the whole set and let the guard compare sets.
  const jobsFor = (gate) => jobs.filter((j) => (jobText.get(j) ?? "").includes(gate)).sort();

  const rules = [];
  const dangling = [];
  const unwired = [];

  for (const r of RULES) {
    const enforcement = r.enforcement.map((e) => {
      const exists = existsSync(join(root, e.gate));
      const lane = jobsFor(e.gate);
      if (!exists) dangling.push(`${r.id}: ${e.gate}`);
      else if (!lane.length) unwired.push(`${r.id}: ${e.gate}`);
      return { ...e, exists, jobs: lane };
    });
    rules.push({
      id: r.id,
      rule: r.rule,
      why: r.why,
      enforcement,
    });
  }

  // A rulebook whose enforcement is a file that does not exist, or a check that runs in
  // no lane, is the thing that got this row started. Fail the build, not the reader.
  if (dangling.length) {
    throw new Error(`agent-rules cites gates that do not exist:\n  ${dangling.join("\n  ")}`);
  }
  if (unwired.length) {
    throw new Error(`agent-rules cites gates that run in no CI lane (wire them, or drop the claim):\n  ${unwired.join("\n  ")}`);
  }

  return {
    version: AGENT_RULES_VERSION,
    name: "contour-agent-rules",
    audience: "an agent generating or reviewing UI code that uses Contour",
    statement:
      "Each rule names the check that enforces it, and that check is verified at build time to exist and to run in a CI lane. Rules are ordered as a working sequence: read this file, then the contracts, then write code, then run the enforcing command for what you touched. Counts are deliberately absent: the numbers an agent needs are published in contour.components.json and contour.tokens.json, which are derived from tools/lib/inventory.mjs and re-checked by their own gates, so restating one here would create a second copy of one fact. Commands assume the repository checkout, not the installed package: a consumer installs src/ and dist/ and cannot run the audit harnesses, which need a browser driver and npm-installed dependencies.",
    source: "tools/lib/agent-rules.mjs",
    ciFile: CI_FILE,
    jobs,
    rules,
  };
}

export const agentRulesJson = (value) => `${JSON.stringify(value, null, 2)}\n`;
